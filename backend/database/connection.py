"""
Database connection setup and PostgreSQL schema initialization. This module defines the shared connection pool and row type aliases, then creates
the users, directories, and files tables when imported.
"""

from datetime import datetime
from typing import cast

from psycopg import Connection
from psycopg.rows import dict_row
from psycopg_pool import ConnectionPool

from core.utils.env import DATABASE_URL

try:
    UserDict = dict[str, str | datetime]
    DirectoryDict = dict[str, int | str | datetime | None]
    FileDict = dict[str, int | str | datetime | list[str] | None]

    POOL: ConnectionPool[Connection[dict[str, int | str | datetime | list[str] | None]]] = cast(
        ConnectionPool[Connection[dict[str, int | str | datetime | list[str] | None]]], cast(object, ConnectionPool(
            DATABASE_URL,
            kwargs={"row_factory": dict_row},
        ))
    )

    with POOL.connection() as connection:
        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS users (
                username   TEXT PRIMARY KEY,
                password   TEXT        NOT NULL,
                first_name TEXT        NOT NULL,
                last_name  TEXT        NOT NULL,
                created_at TIMESTAMPTZ NOT NULL
            );

            CREATE TABLE IF NOT EXISTS directories (
                id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                path        TEXT        NOT NULL,
                modified_at TIMESTAMPTZ NOT NULL,
                deleted_at  TIMESTAMPTZ,
                username    TEXT        NOT NULL,

                CONSTRAINT fk_directories_user
                    FOREIGN KEY (username)
                        REFERENCES users (username),

                CONSTRAINT unique_directory_path
                    UNIQUE (path, username)
            );

            CREATE TABLE IF NOT EXISTS files (
                id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                directory_id BIGINT      NOT NULL,
                name         TEXT        NOT NULL,
                type         TEXT        NOT NULL,
                size         BIGINT      NOT NULL,
                modified_at  TIMESTAMPTZ NOT NULL,
                data_center  TEXT        NOT NULL,
                links        TEXT[]      NOT NULL,
                deleted_at   TIMESTAMPTZ,
                username     TEXT        NOT NULL,

                CONSTRAINT fk_files_directory
                    FOREIGN KEY (directory_id)
                        REFERENCES directories (id),

                CONSTRAINT fk_files_user
                    FOREIGN KEY (username)
                        REFERENCES users (username)
            );

            CREATE TABLE IF NOT EXISTS video_processing_jobs (
                file_id BIGINT PRIMARY KEY,
                status TEXT NOT NULL DEFAULT 'queued',
                stage TEXT NOT NULL DEFAULT 'queued',
                progress DOUBLE PRECISION NOT NULL DEFAULT 0,
                message TEXT NOT NULL DEFAULT 'Waiting for video processing.',
                processed_seconds DOUBLE PRECISION NOT NULL DEFAULT 0,
                duration DOUBLE PRECISION NOT NULL DEFAULT 0,
                bytes_downloaded BIGINT NOT NULL DEFAULT 0,
                source_size BIGINT NOT NULL DEFAULT 0,
                completed_segments INTEGER NOT NULL DEFAULT 0,
                total_segments INTEGER NOT NULL DEFAULT 0,
                attempts INTEGER NOT NULL DEFAULT 0,
                error TEXT,
                created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                started_at TIMESTAMPTZ,
                finished_at TIMESTAMPTZ,
                CONSTRAINT fk_video_processing_job_file
                    FOREIGN KEY (file_id)
                        REFERENCES files (id)
                        ON UPDATE CASCADE
                        ON DELETE CASCADE,
                CONSTRAINT chk_video_processing_status
                    CHECK (status IN ('queued', 'preparing', 'processing', 'ready', 'failed'))
            );

            CREATE INDEX IF NOT EXISTS idx_video_processing_jobs_queue
                ON video_processing_jobs (status, created_at, file_id);

            ALTER TABLE video_processing_jobs
                DROP CONSTRAINT IF EXISTS chk_video_processing_status;
            ALTER TABLE video_processing_jobs
                ADD CONSTRAINT chk_video_processing_status
                CHECK (status IN ('queued', 'preparing', 'processing', 'ready', 'failed'));

            CREATE TABLE IF NOT EXISTS processed_videos (
                id BIGINT PRIMARY KEY,
                data_center TEXT NOT NULL,
                pack_size BIGINT NOT NULL,
                pack_links TEXT[] NOT NULL,
                media_info JSONB NOT NULL,
                assets JSONB NOT NULL,
                processed_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
                CONSTRAINT fk_processed_video_file
                    FOREIGN KEY (id)
                        REFERENCES files (id)
                        ON UPDATE CASCADE
                        ON DELETE CASCADE
            );
            """
        )
        connection.commit()

except Exception as e:
    print(f"Failed to connect: {e}")
