"""
Database connection setup and PostgreSQL schema initialization. This module defines the shared connection pool and row type aliases, then creates
the users, directories, and files tables when imported.
"""

from datetime import datetime
from typing import TypeAlias, cast

from psycopg import Connection
from psycopg.rows import dict_row
from psycopg_pool import ConnectionPool

from core.utils.env import DATABASE_URL

try:
    UserDict: TypeAlias = dict[str, str | datetime]
    DirectoryDict: TypeAlias = dict[str, int | str | datetime | None]
    FileDict: TypeAlias = dict[str, int | str | datetime | list[str] | None]

    POOL: ConnectionPool[Connection[dict[str, int | str | datetime | list[str] | None]]] = cast(
        "ConnectionPool[Connection[dict[str, int | str | datetime | list[str] | None]]]", cast("object", ConnectionPool(
            DATABASE_URL,
            kwargs={"row_factory": dict_row},
        ))
    )

    with POOL.connection() as connection:
        connection.execute(
            """
            CREATE TABLE IF NOT EXISTS users (
                username   TEXT PRIMARY KEY,
                password   TEXT        NOT NULL,
                first_name TEXT        NOT NULL,
                last_name  TEXT        NOT NULL,
                created_at TIMESTAMPTZ NOT NULL
            );

            CREATE TABLE IF NOT EXISTS directories (
                id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                path        TEXT        NOT NULL,
                modified_at TIMESTAMPTZ NOT NULL,
                deleted_at  TIMESTAMPTZ,
                username    TEXT        NOT NULL,

                CONSTRAINT fk_directories_user
                    FOREIGN KEY (username)
                        REFERENCES users (username),

                CONSTRAINT unique_directory_path
                    UNIQUE (path, username)
            );

            CREATE TABLE IF NOT EXISTS files (
                id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                directory_id BIGINT      NOT NULL,
                name         TEXT        NOT NULL,
                type         TEXT        NOT NULL,
                size         BIGINT      NOT NULL,
                modified_at  TIMESTAMPTZ NOT NULL,
                data_center  TEXT        NOT NULL,
                links        TEXT[]      NOT NULL,
                deleted_at   TIMESTAMPTZ,
                username     TEXT        NOT NULL,

                CONSTRAINT fk_files_directory
                    FOREIGN KEY (directory_id)
                        REFERENCES directories (id),

                CONSTRAINT fk_files_user
                    FOREIGN KEY (username)
                        REFERENCES users (username)
            );

            """
        )
        connection.commit()

except Exception as e:
    from core.data_center import Database
    from core.utils import sanitize_sensitive_urls, write_log

    write_log(
        "ERROR",
        Database,
        "DATABASE INIT",
        "server",
        f"PostgreSQL connection or schema initialization failed: {type(e).__name__}: "
        f"{sanitize_sensitive_urls(str(e))[:300]}",
    )
